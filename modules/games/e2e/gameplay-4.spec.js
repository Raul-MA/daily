import { appURL } from '../../../tests/support/app-url.mjs';
import { fixtureData } from './fixture-data.js';
import { expect, test } from "@playwright/test";
import { STORAGE_KEY } from "./storage-key.js";
import { createGame, createPlayer, openApp, testIds } from "./helpers.js";
test("first to points ranks the highest live total as leader", async ({ page }) => {
    const now = new Date().toISOString();
    const data = fixtureData('gameplay-3.json', now);
    await page.addInitScript(({ key, data }) => {
        localStorage.setItem(key, JSON.stringify(data));
    }, { key: STORAGE_KEY, data });
    await page.goto(appURL("games", "session"));
    await expect(page.getByTestId(testIds.sessionTotal).first()).toContainText("Leader");
    await expect(page.getByTestId(testIds.sessionTotal).first()).toContainText("232");
    await expect(page.getByTestId(testIds.sessionTotal).first()).toContainText("Majo");
    await expect(page.getByText("Majo leads with 232 - round total 254")).toBeVisible();
});
test("shows first to points target reached as a toast", async ({ page }) => {
    await openApp(page);
    await createPlayer(page, "Raul");
    await createPlayer(page, "Majo");
    await page.getByTestId(testIds.navGames).first().click();
    await page.getByTestId(testIds.gameName).fill("Dutch Blitz");
    await page.getByTestId(testIds.gameMode).selectOption("first_to_points");
    await page.getByTestId(testIds.gameTargetScore).fill("100");
    await page.getByTestId(testIds.gameSave).click();
    await page.getByTestId(testIds.navPlay).first().click();
    await page.getByTestId(testIds.playGameSelect).selectOption({ label: "Dutch Blitz" });
    await page.getByTestId(testIds.playPlayerToggle).nth(0).check();
    await page.getByTestId(testIds.playPlayerToggle).nth(1).check();
    await page.getByTestId(testIds.playStart).click();
    await page.getByTestId(testIds.scoreInput).nth(1).fill("100");
    await page.getByTestId(testIds.scoreInput).nth(1).blur();
    await expect(page.getByTestId(testIds.appToast)).toContainText("Target reached. You can finish the session now.");
    await page.waitForTimeout(3900);
    await expect(page.getByTestId(testIds.appToast)).toContainText("Target reached. You can finish the session now.");
    await expect(page.locator(".notice", { hasText: "Target reached. You can finish the session now." })).toHaveCount(0);
});
test("records win loss tie results", async ({ page }) => {
    await openApp(page);
    await createPlayer(page, "Ada");
    await createPlayer(page, "Grace");
    await createGame(page, "Chess", "win_loss_tie");
    await page.getByTestId(testIds.navPlay).first().click();
    await page.getByTestId(testIds.playGameSelect).selectOption({ label: "Chess" });
    await page.getByTestId(testIds.playPlayerToggle).nth(0).check();
    await page.getByTestId(testIds.playPlayerToggle).nth(1).check();
    await page.getByTestId(testIds.playStart).click();
    await page.getByTestId(testIds.outcomeSelect).nth(0).selectOption("win");
    await page.getByTestId(testIds.outcomeSelect).nth(1).selectOption("loss");
    page.once("dialog", (dialog) => dialog.accept());
    await page.getByTestId(testIds.finishSession).click();
    await expect(page.getByTestId(testIds.historyItem).filter({ hasText: "Chess" })).toContainText("Winner: Ada");
});
test("preserves scoring settings while collaborative mode is enabled", async ({ page }) => {
    await openApp(page);
    await page.getByTestId(testIds.navGames).first().click();
    await page.getByTestId(testIds.gameName).fill("The Crew");
    await page.getByTestId(testIds.gameMode).selectOption("first_to_points");
    await page.getByTestId(testIds.gameTargetScore).fill("77");
    await page.getByTestId(testIds.gameCollaborative).check();
    await expect(page.getByTestId(testIds.gameMode)).toHaveCount(0);
    await expect(page.getByTestId(testIds.gameTargetScore)).toHaveCount(0);
    await page.getByTestId(testIds.gameSave).click();
    await expect(page.getByTestId(testIds.gameItem).filter({ hasText: "The Crew" })).toContainText("Collaborative · shared win/loss");
    await page.getByTestId(testIds.gameItem).filter({ hasText: "The Crew" }).getByRole("button", { name: "Edit" }).click();
    await page.getByTestId(testIds.gameCollaborative).uncheck();
    await expect(page.getByTestId(testIds.gameMode)).toHaveValue("first_to_points");
    await expect(page.getByTestId(testIds.gameTargetScore)).toHaveValue("77");
});
test("records one team result and keeps collaborative stats separate", async ({ page }) => {
    await openApp(page);
    await createPlayer(page, "Ada");
    await createPlayer(page, "Grace");
    await createGame(page, "The Crew", "highest_score_after_rounds", true);
    await page.getByTestId(testIds.navPlay).first().click();
    await page.getByTestId(testIds.playGameSelect).selectOption({ label: "The Crew" });
    await page.getByTestId(testIds.playPlayerToggle).nth(0).check();
    await page.getByTestId(testIds.playPlayerToggle).nth(1).check();
    await page.getByTestId(testIds.playStart).click();
    await expect(page.getByTestId(testIds.collaborativeOutcome)).toBeVisible();
    await expect(page.getByTestId(testIds.scoreInput)).toHaveCount(0);
    await expect(page.getByTestId(testIds.outcomeSelect)).toHaveCount(0);
    page.once("dialog", (dialog) => dialog.accept());
    await page.getByTestId(testIds.finishSession).click();
    await expect(page.getByTestId(testIds.appToast)).toContainText("Choose a team result.");
    await page.getByTestId(testIds.collaborativeOutcome).selectOption("win");
    page.once("dialog", (dialog) => dialog.accept());
    await page.getByTestId(testIds.finishSession).click();
    await expect(page.getByTestId(testIds.historyItem).filter({ hasText: "The Crew" })).toContainText("Team result: Win");
    await page.getByTestId(testIds.navPlay).first().click();
    await page.getByTestId(testIds.playGameSelect).selectOption({ label: "The Crew" });
    await page.getByTestId(testIds.playPlayerToggle).nth(1).uncheck();
    await page.getByTestId(testIds.playStart).click();
    await page.getByTestId(testIds.collaborativeOutcome).selectOption("loss");
    page.once("dialog", (dialog) => dialog.accept());
    await page.getByTestId(testIds.finishSession).click();
    const stored = await page.evaluate((key) => JSON.parse(localStorage.getItem(key)), STORAGE_KEY);
    const collaborativeSessions = stored.sessions.filter((session) => session.isCollaborative);
    expect(collaborativeSessions).toHaveLength(2);
    expect(collaborativeSessions.every((session) => session.rounds.length === 0 && session.results.length === 0)).toBe(true);
    expect(collaborativeSessions.every((session) => session.winnerPlayerIds.length === 0)).toBe(true);
    await page.getByTestId(testIds.navStats).first().click();
    const adaStats = page.getByTestId(testIds.statsView).locator(".stat-card").filter({ hasText: "Ada" });
    const graceStats = page.getByTestId(testIds.statsView).locator(".stat-card").filter({ hasText: "Grace" });
    await expect(adaStats).toContainText("0-0-0");
    await expect(adaStats).toContainText("1-1");
    await expect(graceStats).toContainText("1-0");
    await expect(page.getByTestId(testIds.headToHeadSection)).toContainText("Shared games");
    await expect(page.getByTestId(testIds.headToHeadSection)).toContainText("0");
    const gameStats = page.getByTestId(testIds.gameStatsView).locator(".stat-card").filter({ hasText: "The Crew" });
    await expect(gameStats).toContainText("1-1");
});
