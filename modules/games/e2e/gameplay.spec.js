test("shows only scoring fields required by selected game mode", async ({ page }) => {
    await openApp(page);
    await page.getByTestId(testIds.navGames).first().click();
    await expect(page.getByTestId(testIds.gameRoundCount)).toBeVisible();
    await expect(page.getByTestId(testIds.gameTargetScore)).toHaveCount(0);
    await page.getByTestId(testIds.gameMode).selectOption("first_to_points");
    await expect(page.getByTestId(testIds.gameTargetScore)).toBeVisible();
    await expect(page.getByTestId(testIds.gameRoundCount)).toHaveCount(0);
    await page.getByTestId(testIds.gameMode).selectOption("win_loss_tie");
    await expect(page.getByTestId(testIds.gameRoundCount)).toHaveCount(0);
    await expect(page.getByTestId(testIds.gameTargetScore)).toHaveCount(0);
});
test("hides game form while a session is active", async ({ page }) => {
    await openApp(page);
    await seedScoreGame(page);
    await startScoreSession(page);
    await page.getByTestId(testIds.navGames).first().click();
    await expect(page.getByTestId(testIds.gameForm)).toHaveCount(0);
    const gameRow = page.getByTestId(testIds.gameItem).filter({ hasText: "Azul" });
    await expect(gameRow).toBeVisible();
    await expect(gameRow.getByRole("button", { name: "Edit" })).toBeDisabled();
    await expect(gameRow.getByRole("button", { name: "Archive" })).toBeDisabled();
});
test("hides play setup form while a session is active", async ({ page }) => {
    await openApp(page);
    await seedScoreGame(page);
    await startScoreSession(page);
    await page.getByTestId(testIds.navPlay).first().click();
    await expect(page.getByTestId(testIds.navSession).filter({ hasText: "Resume" })).toBeVisible();
    await expect(page.getByTestId(testIds.playGameSelect)).toHaveCount(0);
    await expect(page.getByTestId(testIds.playStart)).toHaveCount(0);
    await expect(page.getByTestId(testIds.playPlayerToggle)).toHaveCount(0);
});
test("excludes archived players from new play setup without deleting history", async ({ page }) => {
    await openApp(page);
    await createPlayer(page, "Ada");
    await createPlayer(page, "Grace");
    await createPlayer(page, "Majo");
    await createGame(page, "Azul");
    await page.getByTestId(testIds.navPlay).first().click();
    await page.getByTestId(testIds.playGameSelect).selectOption({ label: "Azul" });
    await page.getByTestId(testIds.playPlayerToggle).nth(0).check();
    await page.getByTestId(testIds.playPlayerToggle).nth(1).check();
    await page.getByTestId(testIds.playStart).click();
    page.once("dialog", (dialog) => dialog.accept());
    await page.getByTestId(testIds.finishSession).click();
    await page.getByTestId(testIds.navPlayers).first().click();
    page.once("dialog", (dialog) => dialog.accept());
    await page.getByTestId(testIds.playerItem).filter({ hasText: "Ada" }).getByRole("button", { name: "Archive" }).click();
    await expect(page.getByTestId(testIds.playerItem).filter({ hasText: "Ada" })).toHaveCount(0);
    await page.getByTestId(testIds.navSettings).first().click();
    await page.getByLabel("Show archived games and players").check();
    await page.getByTestId(testIds.navPlayers).first().click();
    await expect(page.getByTestId(testIds.playerItem).filter({ hasText: "Ada" })).toContainText("Archived");
    await page.getByTestId(testIds.navPlay).first().click();
    await expect(page.getByTestId(testIds.playPlayerToggle)).toHaveCount(2);
    await expect(page.getByText("Ada")).toHaveCount(0);
    await expect(page.getByTestId(testIds.playPlayerToggle).nth(0)).toBeChecked();
    await page.getByTestId(testIds.playStart).click();
    await expect(page.getByTestId(testIds.appToast)).toContainText("Choose at least two players.");
});
test("shows app messages as dismissible fixed toasts", async ({ page }) => {
    await openApp(page);
    await createGame(page, "Azul");
    await createPlayer(page, "Ada");
    await page.getByTestId(testIds.navPlay).first().click();
    await page.getByTestId(testIds.playPlayerToggle).first().check();
    await page.getByTestId(testIds.playStart).click();
    const toast = page.getByTestId(testIds.appToast);
    await expect(toast).toContainText("Choose at least two players.");
    await expect(await toast.evaluate((node) => getComputedStyle(node.closest(".toast-stack")).position)).toBe("fixed");
    await expect(toast).toHaveCSS("border-left-color", "rgb(159, 45, 32)");
    await toast.click();
    await expect(toast).toHaveCount(0);
});
