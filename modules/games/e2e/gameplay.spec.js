import { expect, test } from "@playwright/test";
import { createGame, createPlayer, openApp, seedScoreGame, startScoreSession, testIds } from "./helpers.js";
test("creates edits and archives a player", async ({ page }) => {
    await openApp(page);
    await createPlayer(page, "Ada");
    const row = page.getByTestId(testIds.playerItem).filter({ hasText: "Ada" });
    await row.getByRole("button", { name: "Edit" }).click();
    await page.getByTestId(testIds.playerName).fill("Ada Lovelace");
    await page.getByTestId(testIds.playerSave).click();
    await expect(page.getByTestId(testIds.playerItem).filter({ hasText: "Ada Lovelace" })).toBeVisible();
    page.once("dialog", (dialog) => dialog.accept());
    await page.getByTestId(testIds.playerItem).filter({ hasText: "Ada Lovelace" }).getByRole("button", { name: "Archive" }).click();
    await expect(page.getByTestId(testIds.playerItem)).toHaveCount(0);
});
