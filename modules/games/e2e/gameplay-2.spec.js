import { expect, test } from "@playwright/test";
import { STORAGE_KEY } from "./storage-key.js";
import { openApp, seedScoreGame, startScoreSession, testIds } from "./helpers.js";
test("keeps history filters collapsed and summarizes active filters", async ({ page }) => {
    await openApp(page);
    await seedScoreGame(page);
    await startScoreSession(page);
    page.once("dialog", (dialog) => dialog.accept());
    await page.getByTestId(testIds.finishSession).click();
    await expect(page.getByTestId(testIds.historyFilterToggle)).toHaveText("Show filters");
    await expect(page.getByTestId(testIds.historyFilterSummary)).toContainText("No filters");
    await expect(page.getByTestId(testIds.historySearch)).toHaveCount(0);
    await page.getByTestId(testIds.historyFilterToggle).click();
    await expect(page.getByTestId(testIds.historyFilterToggle)).toHaveText("Hide filters");
    await expect(page.getByTestId(testIds.historySearch)).toBeVisible();
    await page.getByTestId(testIds.historyGameFilter).selectOption({ label: "Azul" });
    await expect(page.getByTestId(testIds.historyFilterSummary)).toContainText("Game: Azul");
});
test("starts enters edits and finishes a score session", async ({ page }) => {
    await openApp(page);
    await seedScoreGame(page);
    await startScoreSession(page);
    const firstScore = page.getByTestId(testIds.scoreInput).nth(0);
    const secondScore = page.getByTestId(testIds.scoreInput).nth(1);
    const firstRoundId = await firstScore.getAttribute("data-round-id");
    const firstPlayerId = await firstScore.getAttribute("data-player-id");
    const secondPlayerId = await secondScore.getAttribute("data-player-id");
    const storedScore = async (playerId) => page.evaluate(({ key, roundId, playerId }) => {
        const data = JSON.parse(localStorage.getItem(key));
        return data.sessions[0].rounds.find((round) => round.id === roundId).scores[playerId];
    }, { key: STORAGE_KEY, roundId: firstRoundId, playerId });
    await firstScore.click();
    await page.keyboard.type("10+5*2");
    await expect(page.getByTestId(testIds.scorePreview).nth(0)).toHaveText("Total: 20");
    await page.keyboard.press("Enter");
    await expect(firstScore).toHaveValue("20");
    expect(await storedScore(firstPlayerId)).toBe(20);
    expect(typeof (await storedScore(firstPlayerId))).toBe("number");
    await secondScore.fill("5+");
    await expect(page.getByTestId(testIds.scorePreview).nth(1)).toHaveText("Invalid");
    await secondScore.blur();
    expect(await storedScore(secondPlayerId)).toBe(0);
    await secondScore.fill(" 7.9 / 2 + --3 * 4 ");
    await expect(page.getByTestId(testIds.scorePreview).nth(1)).toHaveText("Total: 15");
    await secondScore.blur();
    await expect(secondScore).toHaveValue("15");
    expect(await storedScore(secondPlayerId)).toBe(15);
    await secondScore.fill("30/2-18");
    await expect(page.getByTestId(testIds.scorePreview).nth(1)).toHaveText("Total: -3");
    await secondScore.blur();
    expect(await storedScore(secondPlayerId)).toBe(-3);
    await expect(page.getByText("20").first()).toBeVisible();
    await page.getByTestId(testIds.addRound).click();
    await expect(page.getByText("Round 2")).toBeVisible();
    page.once("dialog", (dialog) => dialog.accept());
    await page.getByTestId(testIds.finishSession).click();
    await expect(page.getByTestId(testIds.historyItem).filter({ hasText: "Azul" })).toBeVisible();
    await page.getByTestId(testIds.navStats).first().click();
    await expect(page.getByTestId(testIds.statsView)).toContainText("Ada");
    await expect(page.getByTestId(testIds.headToHeadSection)).toContainText("Head to head");
    const headToHeadTop = await page.getByTestId(testIds.headToHeadSection).boundingBox();
    const statsTop = await page.getByTestId(testIds.statsView).boundingBox();
    expect(headToHeadTop.y).toBeLessThan(statsTop.y);
});
test("opens completed game details without editing first", async ({ page }) => {
    await openApp(page);
    await seedScoreGame(page);
    await startScoreSession(page);
    await page.getByTestId(testIds.scoreInput).nth(0).fill("12");
    await page.getByTestId(testIds.scoreInput).nth(0).blur();
    await page.getByTestId(testIds.scoreInput).nth(1).fill("9");
    await page.getByTestId(testIds.scoreInput).nth(1).blur();
    await page.getByTestId(testIds.addRound).click();
    await page.getByTestId(testIds.scoreInput).nth(2).fill("4");
    await page.getByTestId(testIds.scoreInput).nth(2).blur();
    await page.getByTestId(testIds.scoreInput).nth(3).fill("15");
    await page.getByTestId(testIds.scoreInput).nth(3).blur();
    page.once("dialog", (dialog) => dialog.accept());
    await page.getByTestId(testIds.finishSession).click();
    const historyRow = page.getByTestId(testIds.historyItem).filter({ hasText: "Azul" });
    await historyRow.locator(".history-main").click();
    await expect(page).toHaveURL(/#\/game\//);
    await expect(page.getByTestId(testIds.gameDetail)).toContainText("Winner: Grace");
    await expect(page.getByTestId(testIds.gameDetailRound)).toHaveCount(2);
    await expect(page.getByTestId(testIds.gameDetailRound).nth(0)).toContainText("Round 1");
    await expect(page.getByTestId(testIds.gameDetailRound).nth(1)).toContainText("Round 2");
    await expect(page.getByTestId(testIds.gameDetailScore).filter({ hasText: "12" })).toBeVisible();
    await expect(page.getByTestId(testIds.gameDetailScore).filter({ hasText: "15" })).toBeVisible();
    await expect(page.getByTestId(testIds.scoreInput)).toHaveCount(0);
    page.once("dialog", (dialog) => dialog.accept());
    await page.getByRole("button", { name: "Edit" }).click();
    await expect(page.getByTestId(testIds.activeSession)).toBeVisible();
    await expect(page.getByTestId(testIds.scoreInput)).toHaveCount(4);
});
