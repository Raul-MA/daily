import assert from 'node:assert/strict';
import { page, LESSONS, route, action, startRecall } from './core.mjs';
await route(`/learn?lesson=${LESSONS[0].id}`, '.practice-setup');
assert.equal(await page.locator('[data-disclosure="duration"]').getAttribute('open'), null);
await page.locator('[data-disclosure="duration"] summary').click();
await page.locator('#practice-minutes').fill('2');
await page.locator('[data-disclosure="duration"] summary').click();
await page.locator('.practice-setup button[type="submit"]').click();
assert.equal(await page.locator('.practice-setup').count(), 1);
assert.equal(await page.locator('#practice-minutes').evaluate(node => node.checkValidity()), false);
assert.equal(await page.locator('[data-disclosure="duration"]').evaluate(node => node.open), true, 'invalid custom duration opens its disclosure');
assert.equal(await page.locator('#practice-minutes').evaluate(node => node === document.activeElement), true);
await page.locator('#practice-minutes').fill('7');
assert.equal(await page.locator('[data-preview="0"]').textContent(), '0:42');
await startRecall();
await action('reveal').click();
await page.clock.runFor(1000);
assert.equal(await page.locator('.practice-answer').count(), 1, 'manual pacing retains the answer');
const reviewState = await page.locator('.practice-question, .practice-answer, [data-clock]').allTextContents();
await page.locator('[data-disclosure="review"] summary').click();
assert.equal(await page.locator('[data-disclosure="review"]').evaluate(node => node.open), true);
assert.deepEqual(await page.locator('.practice-question, .practice-answer, [data-clock]').allTextContents(), reviewState, 'review keeps the same prompt, answer, and clock');
await page.locator('[data-disclosure="review"] summary').click();
assert.deepEqual(await page.locator('.practice-question, .practice-answer, [data-clock]').allTextContents(), reviewState);
