import assert from 'node:assert/strict';
import { page, screenshot, route, action, countIntervals } from './core.mjs';
await screenshot('desktop-recall');
assert.equal(await page.locator('[data-disclosure="pacing"]').evaluate(node => node.open), false);
await page.locator('[data-disclosure="pacing"] summary').click();
await page.locator('#practice-pace').fill('30');
await page.locator('[name="auto"]').check();
await page.clock.runFor(10000);
await action('pause').click();
const pausedClock = await page.locator('[data-clock]').textContent();
const pausedPrompt = await page.locator('[data-prompt-clock]').textContent();
await page.clock.runFor(60000);
assert.equal(await page.locator('[data-clock]').textContent(), pausedClock);
assert.equal(await page.locator('[data-prompt-clock]').textContent(), pausedPrompt);
assert.equal(await page.locator('.practice-answer').count(), 1);
await action('pause').click();
await page.clock.runFor(19000);
assert.equal(await page.locator('.practice-answer').count(), 1, 'pause preserves remaining prompt time');
await page.clock.runFor(1200);
assert.equal(await page.locator('.practice-answer').count(), 0);
await page.locator('#practice-pace').fill('0');
assert.equal(await page.locator('[name="auto"]').isChecked(), false);
assert.match(await page.locator('#practice-pace-validation').textContent(), /1 to 300/);
await page.locator('[data-pace="60"]').click();
assert.equal(await page.locator('[data-pace="60"]').getAttribute('aria-pressed'), 'true');
assert.equal(await page.locator('[data-disclosure="pacing"]').evaluate(node => node.open), true, 'preset preserves expanded pacing options');
await action('prompt').click();
assert.equal(await page.locator('[data-disclosure="pacing"]').evaluate(node => node.open), true, 'new prompt preserves expanded pacing options');
await action('reveal').click();
await page.clock.fastForward(420000);
assert.equal(await page.locator('[data-block-notice]').isVisible(), true);
assert.equal(await page.locator('[data-total-notice]').isVisible(), true);
assert.equal(await page.locator('.practice-answer').count(), 1, 'budget boundaries retain the answer');
await page.evaluate(() => {
    Object.defineProperty(document, 'hidden', { configurable: true, value: true });
    document.dispatchEvent(new Event('visibilitychange'));
});
assert.equal(await action('pause').textContent(), 'Resume');
await page.evaluate(() => {
    delete document.hidden;
    document.dispatchEvent(new Event('visibilitychange'));
});
assert.equal(await action('pause').textContent(), 'Resume', 'returning does not resume automatically');
await action('pause').click();
await page.locator('[name="auto"]').check();
assert.equal(await countIntervals(), 1);
await route('/intervals/exercises', '.exercise-card');
assert.equal(await countIntervals(), 0, 'route cleanup stops guided session timers');
await page.locator('.filter-btn').focus();
await page.keyboard.press('Enter');
assert.equal(await page.locator('.filter-btn').getAttribute('aria-expanded'), 'true');
await page.keyboard.press('Escape');
assert.equal(await page.locator('.filter-btn').getAttribute('aria-expanded'), 'false');
assert.equal(await page.locator('.filter-btn').evaluate(node => node === document.activeElement), true);
await page.locator('.exercise-card').focus();
await page.keyboard.press('Enter');
assert.equal(await page.locator('.exercise-card.revealed').count(), 1);
await page.locator('.auto-advance-seconds').fill('30');
await page.locator('.auto-advance-toggle').click();
await page.clock.runFor(29000);
assert.equal(await page.locator('.exercise-card.revealed').count(), 1);
await page.clock.runFor(1000);
assert.equal(await page.locator('.exercise-card.revealed').count(), 0);
await route('/learn', '.practice-setup');
assert.equal(await countIntervals(), 0, 'route cleanup stops standalone exercise timers');
assert.equal(await page.locator('#app-shell').evaluate(node => node.classList.contains('exercise-mode')), false);
console.log('PASS: custom duration, manual/automatic pacing, pause remainder, soft budgets, visibility, route cleanup, standalone keyboard reveal');
